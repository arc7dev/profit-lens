/**
 * Copies the Inter and JetBrains Mono WOFF2 files (from the @fontsource
 * packages, SIL OFL license) into assets/fonts/ and generates
 * assets/css/fonts.css with the matching @font-face rules.
 *
 * Fonts are self-hosted so wp-admin never calls out to Google Fonts:
 * Profit Lens shouldn't make outbound requests with store data, not even
 * for typography.
 *
 * Usage: npm run fonts (run once after `npm install`, or whenever the
 * @fontsource weights/version pins change).
 */
const fs = require( 'fs' );
const path = require( 'path' );

const ROOT = path.resolve( __dirname, '..' );
const FONTS_OUT = path.join( ROOT, 'assets/fonts' );
const CSS_OUT = path.join( ROOT, 'assets/css/fonts.css' );

const FONTS = [
	{
		pkg: '@fontsource/inter',
		family: 'Inter',
		prefix: 'inter-latin',
		weights: [ 400, 500, 600 ],
	},
	{
		pkg: '@fontsource/jetbrains-mono',
		family: 'JetBrains Mono',
		prefix: 'jetbrains-mono-latin',
		weights: [ 400, 500, 600 ],
	},
];

fs.mkdirSync( FONTS_OUT, { recursive: true } );

let css =
	'/**\n * Generated by bin/copy-fonts.js — do not edit by hand.\n' +
	' * Inter and JetBrains Mono, SIL Open Font License 1.1.\n */\n\n';

for ( const font of FONTS ) {
	const filesDir = path.join( ROOT, 'node_modules', font.pkg, 'files' );

	for ( const weight of font.weights ) {
		const filename = `${ font.prefix }-${ weight }-normal.woff2`;
		const src = path.join( filesDir, filename );
		const dest = path.join( FONTS_OUT, filename );

		if ( ! fs.existsSync( src ) ) {
			throw new Error(
				`Could not find ${ src }. Is ${ font.pkg } installed? Run npm install.`
			);
		}

		fs.copyFileSync( src, dest );

		css += `@font-face {\n`;
		css += `\tfont-family: '${ font.family }';\n`;
		css += `\tfont-style: normal;\n`;
		css += `\tfont-weight: ${ weight };\n`;
		css += `\tfont-display: swap;\n`;
		css += `\tsrc: url('../fonts/${ filename }') format('woff2');\n`;
		css += `}\n\n`;
	}
}

fs.mkdirSync( path.dirname( CSS_OUT ), { recursive: true } );
fs.writeFileSync( CSS_OUT, css );

console.log( `Fonts copied to ${ FONTS_OUT }` );
console.log( `CSS generated at ${ CSS_OUT }` );
